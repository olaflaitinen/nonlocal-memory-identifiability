# Purpose: Generate the reference solutions and the noisy synthetic data of
# every condition of the factorial design, at the reference resolution, so that
# inference at the coarser resolution avoids the inverse crime.
# Manuscript: Section 4.2, Tables 3 and 4; equation (9).
# Inputs: an experiment configuration. Outputs: one HDF5 archive per condition
# under results/raw/<experiment>/ and a tracked summary under results/summary/.

import argparse  # Command line interface of the experiment script.
import sys  # Process exit status of the experiment script.
from pathlib import Path  # Portable filesystem paths.

import numpy as np  # Numerical arrays and random number generation.

from nmi.config import load_experiment_config  # Configuration loader with base inheritance.
from nmi.design import design_1d  # Construction of the factorial design.
from nmi.io import ensure_dir, run_metadata, write_csv, write_hdf5  # Output writers.
from nmi.observation import generate_condition_data  # Reference solve and observation model.
from nmi.random_state import generator_from_sequence, spawn_seed_sequences  # Deterministic seeds.


# Parse the command line arguments of the script.
# Arguments:
#   argv (list): command line arguments after the program name.
# Returns:
#   argparse.Namespace: the parsed arguments.
def parse_arguments(argv):
    parser = argparse.ArgumentParser(description="Generate the synthetic data")  # Argument parser.
    parser.add_argument("--config", required=True, help="experiment configuration")  # Configuration.
    parser.add_argument("--condition-index", type=int, default=None, help="one condition")  # Subset.
    parser.add_argument("--output-dir", default=None, help="raw output directory")  # Destination.
    return parser.parse_args(argv)  # Parsed command line arguments of the script.


# Path of the raw output directory of this experiment.
# Arguments:
#   config (dict): the configuration mapping of the run.
#   override (str): an explicit output directory, or None.
# Returns:
#   pathlib.Path: the directory that receives the raw output.
def output_directory(config, override):
    if override:  # An explicit directory was supplied on the command line.
        return ensure_dir(override)  # Use the directory supplied by the caller.
    return ensure_dir(Path("results/raw") / str(config["experiment"]))  # Default location.


# Generate the data of one condition and write it to an HDF5 archive.
# Arguments:
#   condition (dict): one condition of the factorial design.
#   config (dict): the configuration mapping of the run.
#   directory (pathlib.Path): the directory that receives the archive.
#   rng (numpy.random.Generator): generator of the observation noise.
# Returns:
#   dict: a summary record of the condition, written to the tracked summary.
def generate_one(condition, config, directory, rng):
    data = generate_condition_data(condition, config, rng)  # Reference solve and observations.
    # Arrays stored in the archive of this condition.
    arrays = {
        "observations": data["observations"],  # Noisy transient observations.
        "clean": data["clean"],  # Noise free transient values at the same points.
        "times": data["times"],  # Observation times of the sampling design.
        "space_index": data["space_index"],  # Indices of the retained spatial grid points.
        "stationary_observations": data["stationary_observations"],  # Noisy stationary values.
        "stationary_clean": data["stationary_clean"],  # Noise free stationary values.
        "stationary_density": data["stationary_density"],  # Stationary density on the grid.
        "final_density": data["final_density"],  # Final transient state of the reference solve.
    }
    # Metadata entries that identify the condition in the archive.
    extra = {
        "condition_index": condition["index"],  # Stable integer index of the condition.
        "identifier": condition["identifier"],  # Stable textual label of the condition.
        "seed": condition["seed"],  # Deterministic seed of the condition.
        "sigma": data["sigma"],  # Standard deviation of the observation noise.
        "u_max": data["u_max"],  # Largest density of the reference simulation.
        "data_citation": "Synthetic data generated by this repository",  # Provenance statement.
    }
    metadata = run_metadata(config, extra)  # Metadata recorded alongside the archive.
    path = directory / f"data_{condition['index']:03d}.h5"  # Archive of this condition.
    write_hdf5(path, arrays, metadata)  # Write the archive with its metadata.
    # Compact summary record of the condition, written to the tracked summary table.
    return {
        "condition_index": condition["index"],  # Stable integer index of the condition.
        "identifier": condition["identifier"],  # Stable textual label of the condition.
        "kernel": condition["kernel"],  # Detection kernel family of the condition.
        "radius": condition["radius"],  # Perceptual range R of the condition.
        "noise_level": condition["noise_level"],  # Relative noise level eta of the condition.
        "sampling": condition["sampling"],  # Name of the sampling design of the condition.
        "aggregation_ratio": condition["aggregation_ratio"],  # Aggregation ratio kappa.
        "advection": condition["advection"],  # Combined advection strength gamma.
        "sigma": data["sigma"],  # Standard deviation of the observation noise.
        "u_max": data["u_max"],  # Largest density of the reference simulation.
        "min_density": data["min_density"],  # Smallest density of the reference solve.
        "mass_error": data["mass_error"],  # Relative mass error of the reference solve.
        "stationary_residual": data["stationary_residual"],  # Residual of equation (7).
        "dominant_mode": data["dominant_mode"],  # Dominant Fourier mode of the steady state.
        "wall_time": data["wall_time"],  # Wall clock cost of the reference solve.
        "seed": condition["seed"],  # Deterministic seed of the condition.
    }


# Entry point of the synthetic data generation.
# Arguments:
#   argv (list): command line arguments after the program name.
# Returns:
#   int: zero on success.
def main(argv):
    arguments = parse_arguments(argv)  # Parsed command line arguments of the script.
    config = load_experiment_config(arguments.config)  # Merged and validated configuration.
    design = design_1d(config)  # Factorial design of the one-dimensional experiments.
    conditions = design["transient"]  # Transient conditions of the factorial design.
    sequences = spawn_seed_sequences(int(config["design"]["seed"]), len(conditions))  # Seeds.
    directory = output_directory(config, arguments.output_dir)  # Directory of the raw output.
    selected = conditions  # By default every condition of the design is generated.
    if arguments.condition_index is not None:  # A single condition was requested.
        selected = [conditions[int(arguments.condition_index)]]  # Generate that condition only.
    records = []  # Accumulator for the summary records of the generated conditions.
    for condition in selected:  # Generate the data of each selected condition in turn.
        rng = generator_from_sequence(sequences[condition["index"]])  # Seed of the condition.
        records.append(generate_one(condition, config, directory, rng))  # Generate and record.
        print(f"generated condition {condition['index']:03d} {condition['identifier']}")  # Log.
    summary = Path("results/summary") / f"{config['experiment']}_synthetic_data.csv"  # Summary.
    write_csv(summary, records, list(records[0].keys()))  # Write the tracked summary table.
    print(f"wrote {summary} with {len(records)} row(s)")  # Report the location of the summary.
    return 0  # Signal success to the caller.


if __name__ == "__main__":  # Allow the module to be used as a command line script.
    sys.exit(main(sys.argv[1:]))  # Run the experiment and propagate the exit status.
